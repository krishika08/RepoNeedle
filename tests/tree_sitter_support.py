def load_docs(corpus: str):
    root = FIXTURES / corpus
    docs = []
    for p in sorted(root.rglob("*")):
        if p.is_file() and p.suffix != ".json":
            rel = p.relative_to(root).as_posix()
            docs.append(FileDoc(path=rel, content=p.read_text(encoding="utf-8"), is_test="test" in rel.lower()))
    return docs


def fixture_files(corpus: str):
    return {d.path: d.content for d in load_docs(corpus)}


